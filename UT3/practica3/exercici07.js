console.log(5 == "5"); // true, porque == compara si los 2 valores son iguales
console.log(5 === "5"); // false por que === compara si los 2 valores son exactamente iguales.
console.log(0 == false); // true, porque == por que 0 es false, entonce la solucion es true
console.log(0 === false); // false, porque === por que 0 es un numero y false es un booleano. solucion false