/* un operador unari es un operador que actua sobre un sol operant. Per exemple, el operador negatiu (-) es un operador unari que canvia el signe d'un nombre y el operador binari es un operador que actua sobre dos operants. Per exemple, l'operador suma (+) es un operador binari que suma dos nombres*/

